/** 群聊代码禁令的**判据**（判定本身，不含措辞）。
 *
 * 为什么单独抽出来：`qq_send_text` 与 `qq_reply_quote` 用的是同一条正则，各自抄了
 * 一份——改一处忘一处就会出现"普通发能拦、引用发能过"这种洞（这个仓踩过同类的洞：
 * 同一个发送意图，两个工具两套目标校验规则）。
 *
 * 这里只给"像不像代码"，**措辞与后续动作留在各自的工具里**：两个工具的回话不一样
 * （引用回复要说"群里用引用只回一句"），而 P4 的规矩是行为不变。
 */

/**
 * 这段文本看起来像代码吗。
 *
 * 判据刻意宽松：围栏、HTML/XML 标签、以及几种语言的关键字开头。误判的代价是
 * 她改用私信发代码（有一条明确的替代路径），漏判的代价是把工作区内容贴进群里。
 */
export function looksLikeCode(text: string): boolean {
  return /```|<[a-z][a-z0-9]*>|function |const |import |def |#include/i.test(text)
}
